const KK_MONTHS = ["қаңтар", "ақпан", "наурыз", "сәуір", "мамыр", "маусым", "шілде", "тамыз", "қыркүйек", "қазан", "қараша", "желтоқсан"];

const LangContext = createContext(null);

export function LangProvider({ lang, children }) {
  const t = (key, vars) => {
    let s = dict[lang][key] ?? dict.ru[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
    return s;
  };
  // Двуязычное поле из API: tr(obj, "title") -> obj.title_kk / obj.title_ru, с запасным языком
  const tr = (obj, field) => {
    if (!obj) return "";
    const other = lang === "kk" ? "ru" : "kk";
    return obj[`${field}_${lang}`] || obj[`${field}_${other}`] || "";
  };
  const path = (p = "") => `/${lang}${p ? "/" + p.replace(/^\//, "") : ""}`;
  const locale = lang === "kk" ? "kk-KZ" : "ru-RU";
  const fmtDate = (value, withTime = false) => {
    if (!value) return "";
    const d = new Date(value);
    const time = withTime
      ? `, ${String(d.getHours()).padStart(2, "0")}:${String(d.getMinutes()).padStart(2, "0")}`
      : "";
    // Не во всех браузерах есть казахская локаль, поэтому месяцы — вручную
    if (lang === "kk") return `${d.getFullYear()} ж. ${d.getDate()} ${KK_MONTHS[d.getMonth()]}${time}`;
    return new Intl.DateTimeFormat(locale, { day: "numeric", month: "long", year: "numeric" }).format(d) + time;
  };
  const years = (n) => {
    if (lang === "kk") return `${n} жыл`;
    const m10 = n % 10, m100 = n % 100;
    const w = m10 === 1 && m100 !== 11 ? "год" : m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? "года" : "лет";
    return `${n} ${w}`;
  };
  return <LangContext.Provider value={{ lang, t, tr, path, fmtDate, years }}>{children}</LangContext.Provider>;
}

export function useLang() {
  return useContext(LangContext);
}
